#!/usr/bin/env node
/**
 * node scripts/measure-card-ground.mjs
 *
 * Regenerates `src/viral/draw/card-bands.ts` — the brightness of every ground,
 * band by band, across the 1080x1350 CARD frame.
 *
 * 🪤🪤 THIS EXISTS BECAUSE `ground-bands.ts` CANNOT BE REUSED. That file
 * measures the covered 1080x1920 frame. `cover` at 4:5 keeps a different crop
 * of the same plate — a wider, shorter window — so the same JPEG has different
 * numbers here. Reading the 9:16 bands for a 4:5 card would gate against
 * pixels this card never shows. ⛔ Do not "unify" the two.
 *
 * 🪤 Its sibling measures only the copy strip, because a quiet video puts type
 * in one band of the frame. A card is text edge to edge, so this measures the
 * WHOLE frame in 10 bands — there is no strip to exempt.
 *
 * ⭐ A still has ONE frame, so unlike the video path there is no GROUND_DRIFT
 * zoom moving the ground under the type between measurement and render. What
 * this file reports is what ships.
 */
import { execFile } from "node:child_process";
import { readdir, writeFile } from "node:fs/promises";
import { promisify } from "node:util";

const run = promisify(execFile);
const W = 1080;
const H = 1350;
const BANDS = 10;

const bandRows = (i) => [Math.round((H * i) / BANDS), Math.round((H * (i + 1)) / BANDS)];

const measure = async (file) => {
  const { stdout } = await run(
    "ffmpeg",
    [
      "-v", "error",
      "-i", `public/grounds/${file}`,
      "-vf", `scale=${W}:${H}:force_original_aspect_ratio=increase,crop=${W}:${H}`,
      "-f", "rawvideo", "-pix_fmt", "rgb24", "-",
    ],
    { encoding: "buffer", maxBuffer: W * H * 3 * 4 },
  );
  const px = stdout;
  return Array.from({ length: BANDS }, (_, b) => {
    const [y0, y1] = bandRows(b);
    let r = 0, g = 0, bl = 0, n = 0;
    for (let y = y0; y < y1; y++) {
      for (let x = 0; x < W; x++) {
        const i = (y * W + x) * 3;
        r += px[i]; g += px[i + 1]; bl += px[i + 2];
        n++;
      }
    }
    return [Math.round((r / n) * 10) / 10, Math.round((g / n) * 10) / 10, Math.round((bl / n) * 10) / 10];
  });
};

const files = (await readdir("public/grounds")).filter((f) => f.endsWith(".jpg")).sort();
const rows = [];
for (const f of files) {
  const name = f.replace(/\.jpg$/, "");
  rows.push([name, await measure(f)]);
  process.stderr.write(`measured ${name}\n`);
}

const body = rows
  .map(([name, bands]) => `  "${name}": [\n${bands.map((b) => `    [${b.join(", ")}],`).join("\n")}\n  ],`)
  .join("\n");

await writeFile(
  "src/viral/draw/card-bands.ts",
  `// GENERATED by scripts/measure-card-ground.mjs — do not edit by hand.
//
// Mean sRGB of each ground in ${BANDS} horizontal bands across the WHOLE covered
// ${W}x${H} card frame — a card carries text edge to edge, so there is no copy
// strip to exempt the way the 9:16 quiet frame has one.
//
// 🪤 These are NOT the numbers in quiet/ground-bands.ts and must not be swapped
// for them: \`cover\` at 4:5 keeps a different crop of the same plate.

export const CARD_WIDTH = ${W};
export const CARD_HEIGHT = ${H};
export const CARD_BANDS = ${BANDS};

export const CARD_GROUND_BANDS: Record<string, [number, number, number][]> = {
${body}
};
`,
);
process.stderr.write(`wrote src/viral/draw/card-bands.ts (${rows.length} grounds)\n`);
