#!/usr/bin/env node
/**
 * node scripts/measure-grounds.mjs
 *
 * Regenerates `src/viral/quiet/ground-bands.ts` — the measured brightness of
 * every quiet ground, band by band, down the strip of the frame where the copy
 * actually sits.
 *
 * ⭐⭐⭐ WHY THIS EXISTS AT ALL. `checkTextContrast` has to know how bright the
 * photograph is behind the type, and a unit test cannot decode a JPEG. So the
 * measurement is done ONCE, here, with ffmpeg, and checked in as data the gate
 * reads. Re-run it whenever a ground is added or re-graded.
 *
 * 🪤 THE COVER TRANSFORM IS PART OF THE MEASUREMENT, NOT A DETAIL. `QuietVideo`
 * draws grounds with `objectFit: "cover"`, and the plates are NOT all 1080x1920
 * — `dawn-a` is 1152x2048. Measuring the file instead of the covered frame
 * measures pixels the viewer never sees. `scale=...:force_original_aspect_ratio
 * =increase,crop=1080:1920` is exactly what `cover` does.
 *
 * 🪤 MEASURED AT scale = 1, i.e. THE FIRST FRAME OF THE SCENE. `GROUND_DRIFT`
 * zooms the plate by up to 4.5% across the hold, which moves the ground under
 * the type a little. The stated limit of this data is that it describes the
 * start of the hold, not every frame of it.
 */
import { execFile } from "node:child_process";
import { readdir, writeFile } from "node:fs/promises";
import { promisify } from "node:util";

const run = promisify(execFile);
const W = 1080;
const H = 1920;

// The strip the copy occupies, measured off real renders of V58: the type ran
// y 721..1200 and x 154..922 across a 3-row line with a 2-row under-line. The
// window below adds a margin on every side.
export const COPY_TOP = 700;
export const COPY_BOTTOM = 1220;
export const COPY_LEFT = 140;
export const COPY_RIGHT = 940;
export const BANDS = 8;

const bandRows = (i) => {
  const span = (COPY_BOTTOM - COPY_TOP) / BANDS;
  return [Math.round(COPY_TOP + i * span), Math.round(COPY_TOP + (i + 1) * span)];
};

const measure = async (file) => {
  const { stdout } = await run(
    "ffmpeg",
    [
      "-v", "error",
      "-i", `public/grounds/${file}`,
      "-vf", `scale=${W}:${H}:force_original_aspect_ratio=increase,crop=${W}:${H}`,
      "-f", "rawvideo", "-pix_fmt", "rgb24", "-",
    ],
    { encoding: "buffer", maxBuffer: W * H * 3 * 4 },
  );
  const px = stdout;
  return Array.from({ length: BANDS }, (_, b) => {
    const [y0, y1] = bandRows(b);
    let r = 0, g = 0, bl = 0, n = 0;
    for (let y = y0; y < y1; y++) {
      for (let x = COPY_LEFT; x < COPY_RIGHT; x++) {
        const i = (y * W + x) * 3;
        r += px[i]; g += px[i + 1]; bl += px[i + 2];
        n++;
      }
    }
    return [Math.round((r / n) * 10) / 10, Math.round((g / n) * 10) / 10, Math.round((bl / n) * 10) / 10];
  });
};

const files = (await readdir("public/grounds")).filter((f) => f.endsWith(".jpg")).sort();
const rows = [];
for (const f of files) {
  const name = f.replace(/\.jpg$/, "");
  rows.push([name, await measure(f)]);
  process.stderr.write(`measured ${name}\n`);
}

const body = rows
  .map(([name, bands]) => `  "${name}": [\n${bands.map((b) => `    [${b.join(", ")}],`).join("\n")}\n  ],`)
  .join("\n");

await writeFile(
  "src/viral/quiet/ground-bands.ts",
  `// GENERATED by scripts/measure-grounds.mjs — do not edit by hand.
//
// Mean sRGB of each quiet ground, PRE-SCRIM, in ${BANDS} horizontal bands down the
// strip where the copy sits (y ${COPY_TOP}..${COPY_BOTTOM}, x ${COPY_LEFT}..${COPY_RIGHT} of the
// covered 1080x1920 frame). \`checkTextContrast\` applies the scrim to these and
// asks whether the ink and the accent word can be read against the result.

export const COPY_TOP = ${COPY_TOP};
export const COPY_BOTTOM = ${COPY_BOTTOM};
export const BANDS = ${BANDS};

/** Vertical position of band \`i\`'s centre, as a fraction of frame height. */
export const bandCentreY = (i: number): number =>
  (COPY_TOP + ((COPY_BOTTOM - COPY_TOP) * (i + 0.5)) / BANDS) / 1920;

export const GROUND_BANDS: Record<string, [number, number, number][]> = {
${body}
};
`,
);
process.stderr.write(`wrote src/viral/quiet/ground-bands.ts (${rows.length} grounds)\n`);
