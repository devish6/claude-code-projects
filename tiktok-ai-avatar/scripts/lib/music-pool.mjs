/**
 * Music pool for the daily pipeline.
 *
 * public/music/ has ~19 files registered in MUSIC (src/lib/brand.ts), but
 * most are slow ambient beds carried over from the original (non-viral) promo
 * set. The viral system's rule is "energy from frame 0" (hard-cut hook lands
 * on near-silence otherwise) -- only four tracks actually meet that bar today:
 * violin-energetic (V01), trend-v02 (V02), starlight-v03 (V03, head-trimmed),
 * ready-v04 (V04). Count against THESE FOUR when applying the 6-track floor,
 * not the full MUSIC registry -- the registry count is misleading.
 */
import { existsSync, mkdirSync, unlinkSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const FAST_TRACKS = ["violinEnergetic", "trendV02", "starlightV03", "readyV04"];
export const POOL_FLOOR = 6;

export const poolHealthy = () => FAST_TRACKS.length >= POOL_FLOOR;

/**
 * Round-robins the fast-track pool, only avoiding an exact repeat of
 * whatever the immediately previous video (any category) used -- "never
 * reuses the same bed two days running" is a day-to-day constraint, not a
 * per-video one, and with only 4 usable tracks for 3 videos/day some
 * within-day reuse is unavoidable until the pool is restocked.
 */
export const nextTrack = (state) => {
  const used = state.videos
    .filter((v) => v.source !== "seed-existing")
    .map((v) => v.music)
    .filter(Boolean);
  const last = used[used.length - 1];
  const lastIdx = FAST_TRACKS.indexOf(last);
  const next = FAST_TRACKS[(lastIdx + 1) % FAST_TRACKS.length];
  return next;
};

const RESTOCK_PATH = (destRoot) => join(destRoot, "MUSIC-RESTOCK.md");

/**
 * Writes (or removes) ~/Desktop/Numevix Videos/Viral/MUSIC-RESTOCK.md based
 * on current pool health. Idempotent -- safe to call every run.
 */
export const syncRestockNote = (destRoot) => {
  const path = RESTOCK_PATH(destRoot);
  if (poolHealthy()) {
    if (existsSync(path)) unlinkSync(path);
    return { wrote: false };
  }
  mkdirSync(destRoot, { recursive: true });
  const body = `# Music pool needs a restock

The daily:viral pipeline counts **${FAST_TRACKS.length} usable tracks** (fast,
full-energy-from-frame-0 beds), below the 6-track floor. It will keep running
on the ${FAST_TRACKS.length} it has, reusing them more than ideal, until this
file is deleted.

## What's missing

Fast, percussive, 100+ BPM-feel tracks that hit full level within ~50ms of
frame 0 -- the hard-cut hook can't open on a fade-in swell. Currently short
2-3 on hand.

## Where to get them

Browse **https://www.tiktok.com/tiktokstudio/sound-library** (requires your
logged-in TikTok Studio session -- this can't be automated) for fast-paced,
upbeat tracks in this style. Download 5-10 candidates.

## What to do with them

1. Drop the files into \`public/music/\`.
2. Register each one in the \`MUSIC\` object in \`src/lib/brand.ts\`, with a
   comment noting source, duration, and whether it needs a head-trim (a track
   that fades in for the first ~2s needs slicing so frame 0 lands on the
   downbeat -- see how \`starlight-v03.mp3\` was handled).
3. Add the new MUSIC key(s) to \`FAST_TRACKS\` in
   \`scripts/lib/music-pool.mjs\`.
4. Run \`npm run daily:viral\` again -- once the pool is >= 6, this file
   deletes itself automatically.

_Generated by scripts/lib/music-pool.mjs. Safe to delete once the pool is
restocked; it will reappear if it drops below 6 again._
`;
  writeFileSync(path, body);
  return { wrote: true, path };
};
