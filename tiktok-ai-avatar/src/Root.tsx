import { Composition, Folder } from "remotion";
import { MoolankPromo } from "./MoolankPromo";
import { MOOLANKS } from "./moolank-data";

import { NameBlockingSuccess, NAME_BLOCKING_DURATION } from "./promos/NameBlockingSuccess";
import { BirthDateNotRandom, BIRTHDATE_DURATION } from "./promos/BirthDateNotRandom";
import { TrueNumber, TRUE_NUMBER_DURATION } from "./promos/TrueNumber";
import { NameVibration, NAME_VIBRATION_DURATION } from "./promos/NameVibration";
import { SecretNumberSuccess, SECRET_NUMBER_DURATION } from "./promos/SecretNumberSuccess";
import { CommentBirthday, COMMENT_BIRTHDAY_DURATION } from "./promos/CommentBirthday";
import { ProductDemo, PRODUCT_DEMO_DURATION } from "./promos/ProductDemo";
import { BirthVsDestiny, BIRTH_VS_DESTINY_DURATION } from "./promos/BirthVsDestiny";
import { WhySeven, WHY_SEVEN_DURATION } from "./promos/WhySeven";
import { BornWithStrengths, BORN_WITH_STRENGTHS_DURATION } from "./promos/BornWithStrengths";
import { Cover } from "./promos/Cover";

import { ViralVideo, type ViralVideoProps } from "./viral/ViralVideo";
import { StoryVideo } from "./viral/StoryVideo";
import { STORY_SCRIPTS } from "./viral/story-scripts";
import { StoryVideo01 } from "./viral/StoryVideo01";
import { STORY_01_DURATION, STORY_01_FPS } from "./viral/story-01-data";
import { MUSIC } from "./lib/brand";
import { ViralCover } from "./viral/ViralCover";
import {
  HOOK_TEST_COMPOSITIONS,
  VIRAL_COVERS,
  VIRAL_TEMPLATES,
} from "./viral/templates";
// Daily pipeline output (npm run daily:viral). V07 onward. Regenerated by
// scripts/lib/templates-gen.mjs from content/daily-state.json -- this import
// is the only line that needs to exist for new daily videos to show up in
// the studio; the file itself is never hand-edited.
import { DAILY_COVERS, DAILY_TEMPLATES } from "./viral/daily-templates";
import { UpiLaunch } from "./viral/UpiLaunch";
import { UPI_COVERS, UPI_TEMPLATES } from "./viral/upi-templates";
import { TalkingHead } from "./talking/TalkingHead";
import { TOTAL_FRAMES as TALKING_TOTAL } from "./talking/script";
import { DISPLAY_HI, UI_HI } from "./viral/fonts";
import { ACT, makeActs } from "./viral/timing";

// 1080x1920, 30fps — vertical short-form for TikTok / Reels / Shorts.
const V = { fps: 30, width: 1080, height: 1920 } as const;

export const RemotionRoot: React.FC = () => {
  return (
    <>
      {/*
        Viral system (src/viral/*) — rebuilt to short-form retention timing:
        hard-cut hooks, ≤1.5s scenes, spring snaps instead of cross-fades.
        The Numevix-Promos folder below is the original slower cut, kept as an
        A/B baseline.
      */}
      {/* Story Friday — the narrative format. One composition per script, so
          a new combination is a data entry rather than a new component. */}
      <Folder name="Story">
        {/*
          Story01 — the image-and-narration format. Duration is DERIVED from the real
          narration timings (story-01-data.ts is generated from ElevenLabs' alignment),
          never hardcoded: change the script, re-run the builder, and the composition
          length follows. The older StoryVideo below is the superseded SVG pilot.
        */}
        <Composition
          id="Story01-NumberRepeats"
          component={StoryVideo01}
          durationInFrames={STORY_01_DURATION}
          fps={STORY_01_FPS}
          width={1080}
          height={1920}
        />
        {Object.values(STORY_SCRIPTS).map((s) => (
          <Composition
            key={s.id}
            id={`Story${s.driver}${s.conductor}`}
            component={StoryVideo}
            durationInFrames={30 * 30}
            fps={30}
            width={1080}
            height={1920}
            defaultProps={{
              driver: s.driver,
              conductor: s.conductor,
              beats: s.beats,
              ctaText: s.ctaText,
              music: MUSIC.voltSlope,
              palette: "ink-violet",
              seconds: 30,
            }}
          />
        ))}
      </Folder>

      <Folder name="Viral">
        {Object.entries({ ...VIRAL_TEMPLATES, ...DAILY_TEMPLATES }).map(([id, props]) => (
          <Composition
            key={id}
            id={id}
            component={ViralVideo}
            /* Per video, and derived at render time rather than from
               defaultProps, so an overridden `structure` actually changes the
               length. This was `ACT.total` for EVERY composition, which is why
               all 28 renders measured exactly 17.450667s and TikTok read the
               set as duplicates. */
            durationInFrames={ACT.total}
            calculateMetadata={({ props: p }) => ({
              durationInFrames: p.structure ? makeActs(p.structure).total : ACT.total,
            })}
            defaultProps={props}
            {...V}
          />
        ))}
      </Folder>

      {/*
        Announcements — product events, not numerology content. Kept OUT of the
        Viral folder on purpose: that folder is an A/B set whose videos share
        an act structure, and averaging an announcement into it would make the
        3-second view rates non-comparable.
      */}
      <Folder name="Viral-Announcements">
        {Object.entries(UPI_TEMPLATES).map(([id, props]) => (
          <Composition
            key={id}
            id={id}
            component={UpiLaunch}
            durationInFrames={ACT.total}
            defaultProps={props}
            {...V}
          />
        ))}
        {Object.entries(UPI_COVERS).map(([id, cover]) => {
          const hindi = UPI_TEMPLATES[id as keyof typeof UPI_TEMPLATES].hindi;
          return (
            <Composition
              key={`${id}-Cover`}
              id={`${id}-Cover`}
              component={ViralCover}
              durationInFrames={60}
              defaultProps={{
                ...cover,
                variant: "identity" as const,
                ...(hindi ? { displayFont: DISPLAY_HI, uiFont: UI_HI } : {}),
              }}
              {...V}
            />
          );
        })}
      </Folder>

      {/*
        A/B set: ten hooks on the SAME V01 body. Ship 2-3 at a time, days
        apart — posting ten near-identical videos at once reads as repetitive
        and splits your own audience across them.
      */}
      <Folder name="Viral-HookTests">
        {Object.entries(HOOK_TEST_COMPOSITIONS).map(([id, props]) => (
          <Composition
            key={id}
            id={id}
            component={ViralVideo}
            durationInFrames={ACT.total}
            defaultProps={props}
            {...V}
          />
        ))}
      </Folder>

      <Folder name="Viral-Covers">
        {Object.entries({ ...VIRAL_COVERS, ...DAILY_COVERS }).map(([id, cover]) => {
          const props =
            (VIRAL_TEMPLATES as Record<string, ViralVideoProps>)[id] ??
            (DAILY_TEMPLATES as Record<string, ViralVideoProps>)[id];
          return (
            <Composition
              key={id}
              id={`${id}-Cover`}
              component={ViralCover}
              durationInFrames={60}
              defaultProps={{
                ...cover,
                variant: props.variant,
              }}
              {...V}
            />
          );
        })}
      </Folder>

      <Folder name="Numevix-Promos">
        <Composition
          id="01-NameBlockingSuccess"
          component={NameBlockingSuccess}
          durationInFrames={NAME_BLOCKING_DURATION}
          {...V}
        />
        <Composition
          id="02-BirthDateNotRandom"
          component={BirthDateNotRandom}
          durationInFrames={BIRTHDATE_DURATION}
          {...V}
        />
        <Composition
          id="03-TrueNumber"
          component={TrueNumber}
          durationInFrames={TRUE_NUMBER_DURATION}
          {...V}
        />
        <Composition
          id="04-NameVibration"
          component={NameVibration}
          durationInFrames={NAME_VIBRATION_DURATION}
          {...V}
        />
        <Composition
          id="05-SecretNumberSuccess"
          component={SecretNumberSuccess}
          durationInFrames={SECRET_NUMBER_DURATION}
          {...V}
        />
        <Composition
          id="06-CommentBirthday"
          component={CommentBirthday}
          durationInFrames={COMMENT_BIRTHDAY_DURATION}
          {...V}
        />
        <Composition
          id="07-ProductDemo"
          component={ProductDemo}
          durationInFrames={PRODUCT_DEMO_DURATION}
          {...V}
        />
        <Composition
          id="08-BirthVsDestiny"
          component={BirthVsDestiny}
          durationInFrames={BIRTH_VS_DESTINY_DURATION}
          {...V}
        />
        <Composition
          id="09-WhySeven"
          component={WhySeven}
          durationInFrames={WHY_SEVEN_DURATION}
          {...V}
        />
        <Composition
          id="10-BornWithStrengths"
          component={BornWithStrengths}
          durationInFrames={BORN_WITH_STRENGTHS_DURATION}
          {...V}
        />
      </Folder>

      <Folder name="Covers">
        <Composition
          id="Cover"
          component={Cover}
          durationInFrames={60}
          fps={30}
          width={1080}
          height={1920}
          defaultProps={{
            variant: "ink" as const,
            kicker: "Numerology",
            title: "IS YOUR NAME",
            accent: "BLOCKING YOU?",
            watermark: "",
          }}
        />
      </Folder>

      {/*
        Talking-head cuts (src/talking/*) — real footage of the founder rather
        than generated scenes. Source clips live in public/talking/, which is
        gitignored: this repo is public and Pages-served.
      */}
      <Folder name="TalkingHead">
        <Composition
          id="M-BirthdayIsEnough"
          component={TalkingHead}
          durationInFrames={TALKING_TOTAL}
          fps={V.fps}
          width={V.width}
          height={V.height}
        />
      </Folder>

      <Folder name="Moolank">
        {Object.values(MOOLANKS)
          .sort((a, b) => a.n - b.n)
          .map((data) => (
            <Composition
              key={data.n}
              id={`Moolank-${data.n}`}
              component={MoolankPromo}
              durationInFrames={900}
              fps={30}
              width={1080}
              height={1920}
              defaultProps={{ data }}
            />
          ))}
      </Folder>
    </>
  );
};
